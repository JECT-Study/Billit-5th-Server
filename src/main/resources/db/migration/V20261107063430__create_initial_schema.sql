CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 회원 번호 **/
    social_provider auth_provider NOT NULL, /** 소셜 제공자 **/
    social_provider_user_id VARCHAR(255), /** 외부 사용자 ID | NULL = 탈퇴로 삭제되었거나 미기록 **/
    nickname VARCHAR(10), /** 닉네임 | NULL = 미입력 **/
    name VARCHAR(50), /** 이름 | NULL = 미입력 **/
    age INTEGER, /** 만 나이 | NULL = 미입력 **/
    gender gender, /** 성별 | NULL = 미입력 **/
    is_treasurer BOOLEAN, /** 총무 여부 | NULL = 미응답 **/
    marketing_push_agreed_at TIMESTAMPTZ, /** 마케팅 푸시 동의 시각 | NULL = 미동의 **/
    marketing_night_push_agreed_at TIMESTAMPTZ, /** 야간 마케팅 푸시 동의 시각 | NULL = 미동의 **/
    ocr_agreed_at TIMESTAMPTZ, /** OCR 동의 시각 | NULL = 동의 기록 없음 | 이력 → member_consent **/
    status member_status NOT NULL, /** 회원 상태 **/
    withdrawn_at TIMESTAMPTZ, /** 탈퇴 시각 | NULL = 탈퇴 기록 없음 **/
    created_at TIMESTAMPTZ NOT NULL, /** 최초 소셜 로그인 시각 **/
    updated_at TIMESTAMPTZ NOT NULL, /** 최종 수정 시각 **/
    CONSTRAINT pk_member PRIMARY KEY (id),
    CONSTRAINT uq_member_nickname UNIQUE (nickname)
);

