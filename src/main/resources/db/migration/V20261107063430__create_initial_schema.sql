    created_at TIMESTAMPTZ NOT NULL, /** 생성 시각 **/
    updated_at TIMESTAMPTZ NOT NULL, /** 최종 수정 시각 **/
    CONSTRAINT pk_trip PRIMARY KEY (id),
    CONSTRAINT uq_trip_invite_code UNIQUE (invite_code)
);

CREATE TABLE trip_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 여행 참여자 자리 ID **/
    trip_id BIGINT NOT NULL, /** 여행 ID → trip.id **/
