CREATE TABLE expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 지출 번호 **/
    trip_id BIGINT NOT NULL, /** 여행 ID → trip.id **/
    idempotency_key UUID NOT NULL, /** 앱에서 발급한 요청 고유키 **/
    name VARCHAR(50) NOT NULL, /** 지출 이름 **/
    split_type split_type NOT NULL, /** 분할 방식 **/
    original_amount BIGINT NOT NULL, /** 할인 전 총액 | currency 최소 단위 정수 (USD 12.34 = 1234) **/
    discount_amount BIGINT DEFAULT 0 NOT NULL, /** 전체 할인액 | currency 최소 단위 정수 **/
    amount BIGINT NOT NULL, /** 최종 결제액 | currency 최소 단위 정수 | original_amount - 품목 할인 합 - discount_amount | 부담액 합과 같음 **/
    currency CHAR(3) NOT NULL, /** 결제 통화 **/
    paid_date DATE NOT NULL, /** 결제 날짜 **/
    payer_trip_member_id BIGINT NOT NULL, /** 결제자 → trip_member.id **/
    created_by_trip_member_id BIGINT NOT NULL, /** 작성자 → trip_member.id **/
    payment_method payment_method NOT NULL, /** 결제수단 **/
    exchange_rate DECIMAL(24,12) NOT NULL, /** 적용 환율 | 결제 통화 1단위 = 원화 N원 **/
    exchange_rate_source rate_source NOT NULL, /** 환율 결정 방식 **/
    exchange_rate_provider VARCHAR(50), /** 자동 환율 제공자 | NULL = 직접 입력 또는 원화 결제 **/
    krw_amount BIGINT NOT NULL, /** 최종 결제액의 원화 환산액 | 단위 = 1원 **/
    edit_lock_owner_trip_member_id BIGINT, /** 수정 잠금 소유자 → trip_member.id | NULL = 소유자 없음 **/
    edit_lock_expires_at TIMESTAMPTZ, /** 수정 잠금 만료 시각 | NULL = 만료 시각 없음 **/
    edit_lock_token UUID, /** 수정 잠금 토큰 | NULL = 토큰 없음 | 수정 시작마다 재발급 **/
    settlement_id BIGINT, /** 잠금 정산 → settlement.id | NULL = 정산 잠금 없음 | 취소 또는 이탈 시 해제 **/
    deleted_at TIMESTAMPTZ, /** 삭제 시각 | NULL = 삭제되지 않음 **/
    created_at TIMESTAMPTZ NOT NULL, /** 생성 시각 **/
    updated_at TIMESTAMPTZ NOT NULL, /** 최종 수정 시각 **/
    CONSTRAINT pk_expense PRIMARY KEY (id),
    CONSTRAINT uq_expense_idempotency_key UNIQUE (idempotency_key)
);

