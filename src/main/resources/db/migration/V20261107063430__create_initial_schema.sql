CREATE TABLE trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 여행 번호 **/
    name VARCHAR(15) NOT NULL, /** 여행 이름 **/
    start_date DATE NOT NULL, /** 여행 시작일 **/
    end_date DATE NOT NULL, /** 여행 종료일 **/
    country_code CHAR(2) NOT NULL, /** 대표 국가 코드 **/
    base_currency CHAR(3) NOT NULL, /** 기본 통화 코드 **/
    member_capacity INTEGER NOT NULL, /** 생성자 포함 총 정원 | 최대 10명 **/
    members_locked_at TIMESTAMPTZ, /** 여행 시작 시각 | NULL = 참여자 초대 중 | 이후 참여자와 정원 수정 불가 **/
