CREATE TABLE apple_refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 고유 식별자 **/
    member_id BIGINT NOT NULL, /** 회원 ID → member.id | 회원당 1개, 다시 로그인해 새 토큰을 받으면 교체 **/
    encrypted_refresh_token VARCHAR(1024) NOT NULL, /** 애플 Refresh Token 암호문 | base64(12바이트 nonce + AES-256-GCM 암호문과 16바이트 태그) | 키 → AUTH_TOKEN_ENCRYPTION_KEY, AAD → apple_refresh_token:{member_id} | 탈퇴 시 애플 연결 해제(revoke)용 **/
    created_at TIMESTAMPTZ NOT NULL, /** 최초 저장 시각 **/
    updated_at TIMESTAMPTZ NOT NULL, /** 최종 교체 시각 **/
    CONSTRAINT pk_apple_refresh_token PRIMARY KEY (id),
    CONSTRAINT uq_apple_refresh_token_member_id UNIQUE (member_id)
);

ALTER TABLE apple_refresh_token
    ADD CONSTRAINT fk_apple_refresh_token_member_id
    FOREIGN KEY (member_id) REFERENCES member (id) ON UPDATE NO ACTION ON DELETE NO ACTION;
