CREATE TYPE login_history_type AS ENUM (
    'LOGIN', /** LOGIN = 새 로그인 세션 발급(소셜 로그인, 가입 완료) **/
    'TOKEN_REFRESH' /** TOKEN_REFRESH = 같은 세션의 토큰 갱신 **/
);

CREATE TABLE login_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 고유 식별자 **/
    member_id BIGINT NOT NULL, /** 회원 ID → member.id **/
    login_type login_history_type NOT NULL, /** 기록한 인증 행동 **/
    ip_address VARCHAR(45), /** 접속 IP 주소(IPv4 또는 IPv6 문자열) | Nginx가 전달한 실제 접속 주소 | NULL = HTTP 요청 밖에서 발급 **/
    occurred_at TIMESTAMPTZ NOT NULL, /** 로그인 또는 갱신 시각 | 3개월이 지나면 매일 삭제 **/
    CONSTRAINT pk_login_history PRIMARY KEY (id)
);

ALTER TABLE login_history
    ADD CONSTRAINT fk_login_history_member_id
    FOREIGN KEY (member_id) REFERENCES member (id) ON UPDATE NO ACTION ON DELETE NO ACTION;

CREATE INDEX idx_login_history_member_id
    ON login_history (member_id);

CREATE INDEX idx_login_history_occurred_at
    ON login_history (occurred_at);
