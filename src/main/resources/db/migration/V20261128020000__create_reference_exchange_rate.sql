CREATE TABLE reference_exchange_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, /** 기준 환율 번호 **/
    provider VARCHAR(50) NOT NULL, /** 환율을 고시한 기관의 코드 | ECB = 유럽중앙은행 **/
    currency CHAR(3) NOT NULL, /** 외화 통화 코드 **/
    rate_date DATE NOT NULL, /** 이 환율을 적용하는 날짜 | 조회 요청의 결제일 **/
    base_date DATE NOT NULL, /** 고시 기관이 환율을 고시한 실제 기준일 | 결제일과 같거나 그 이전 7일 안 **/
    rate DECIMAL(24,12) NOT NULL, /** 고시 기관이 제공한 환율 | 외화 1단위 = 원화 N원 | 반올림하지 않은 원본 **/
    created_at TIMESTAMPTZ NOT NULL, /** 행을 저장한 시각 **/
    CONSTRAINT pk_reference_exchange_rate PRIMARY KEY (id),
    CONSTRAINT uq_reference_exchange_rate_provider_currency_rate_date UNIQUE (provider, currency, rate_date),
    CONSTRAINT ck_reference_exchange_rate_base_date_range CHECK (base_date <= rate_date AND base_date >= rate_date - 7)
);
